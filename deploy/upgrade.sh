#!/usr/bin/env bash
# Upgrade a recognized native installation without moving its configuration or data.
set +x
set -euo pipefail
umask 077
fail() { printf 'Upgrade failed: %s\n' "$*" >&2; exit 1; }
usage() {
    cat <<'HELP'
Usage: upgrade.sh --service-name NAME [--cli-path PATH] [--inspect]
       upgrade.sh --service-name NAME --package-dir DIR [--cli-path PATH] [--yes]
  --inspect          Check the existing layout and print non-secret installation facts
  --backup-dir DIR   Backup parent directory (default: /var/backups/oss-transfer)
  --yes              Confirm the upgrade without prompting
Configuration, service name and database paths are retained. A failed startup restores
files and the database; the old service is restarted only if it was previously active.
HELP
}
here="$(cd "$(dirname "$0")" && pwd)"
service_name='' cli_path='/usr/local/bin/oss-transfer-cli' package_dir='' inspect=0 yes=0
backup_base='/var/backups/oss-transfer'
while [[ $# -gt 0 ]]; do
    case "$1" in
        --help|-h) usage; exit 0;;
        --inspect) inspect=1; shift;;
        --yes) yes=1; shift;;
        --service-name|--cli-path|--package-dir|--backup-dir)
            [[ $# -ge 2 && -n "$2" && "$2" != --* ]] || fail "$1 requires a value"
            case "$1" in --service-name) service_name="${2%.service}";; --cli-path) cli_path="$2";; --package-dir) package_dir="$2";; --backup-dir) backup_base="$2";; esac
            shift 2;;
        *) fail "unknown option: $1";;
    esac
done
[[ "$(uname -s)" == Linux && "$(id -u)" == 0 ]] || fail 'run as root on Linux with systemd'
[[ "$service_name" =~ ^[A-Za-z0-9_-]+$ ]] || fail '--service-name is required'
for dependency in systemctl awk du df cp find findmnt; do command -v "$dependency" >/dev/null || fail "missing dependency: $dependency"; done
safe_path() {
    local path="$1" ancestor
    [[ "$path" =~ ^/[A-Za-z0-9_./-]+$ && "$path" != / && "$path" != *//* && "$path" != */ && ! "$path" =~ (^|/)\.\.?(/|$) ]] || fail 'unsupported path; use absolute paths without spaces, links or dot segments'
    ancestor="$path"
    while [[ "$ancestor" != / ]]; do
        [[ ! -L "$ancestor" ]] || fail "symbolic links are not supported: $ancestor"
        ancestor="$(dirname "$ancestor")"
    done
}
if [[ "$inspect" == 0 ]]; then
    command -v flock >/dev/null || fail 'missing dependency: flock'
    lock_file="/run/lock/oss-transfer-upgrade-$service_name.lock"
    safe_path "$lock_file"
    exec 9> "$lock_file"
    flock -n 9 || fail 'an upgrade of this service is already running'
fi
unit="/etc/systemd/system/$service_name.service"
safe_path "$unit"; safe_path "$cli_path"; safe_path "$backup_base"
[[ -f "$unit" ]] || fail "service file not found: $unit"
[[ "$(systemctl show "$service_name.service" -p FragmentPath --value)" == "$unit" ]] || fail 'service does not use the expected unit file'
[[ -z "$(systemctl show "$service_name.service" -p DropInPaths --value)" ]] || fail 'custom systemd drop-ins require a manual upgrade'
[[ "$(systemctl show "$service_name.service" -p NeedDaemonReload --value)" != yes ]] || fail 'systemd has not loaded the current unit file; run systemctl daemon-reload and retry'
# Accept only the two unit layouts generated by OSS Transfer. Never evaluate unit text.
awk '
    /^\[/{section=$0;next}
    section=="[Service]" && /^[[:space:]]*[^#;[:space:]]/ {
        n=split($0,a,"="); key=a[1]; gsub(/^[[:space:]]+|[[:space:]]+$/,"",key)
        if(n<2 || seen[key]++ || key !~ /^(Type|User|KillMode|WorkingDirectory|ExecStart|ExecStartPre|Restart|RestartSec|StandardOutput|StandardError|TimeoutStopSec|UMask|NoNewPrivileges)$/) exit 1
    }
' "$unit" || fail 'custom systemd service directives require a manual upgrade'
unit_value() {
    awk -v key="$1" '/^\[/{section=$0;next} section=="[Service]" && index($0,key"=")==1 {n++; value=substr($0,length(key)+2)} END {if(n!=1)exit 1;print value}' "$unit"
}
work_dir="$(unit_value WorkingDirectory)" || fail 'expected one WorkingDirectory in the service'
exec_start="$(unit_value ExecStart)" || fail 'expected one ExecStart in the service'
safe_path "$work_dir"
[[ -d "$work_dir" ]] || fail 'service working directory does not exist'
[[ "$(systemctl show "$service_name.service" -p WorkingDirectory --value)" == "$work_dir" ]] || fail 'loaded service working directory differs from the unit file'
[[ "$(unit_value Type)" == simple ]] || fail 'only Type=simple services are supported'
kill_mode="$(unit_value KillMode 2>/dev/null || true)"
[[ -z "$kill_mode" || "$kill_mode" == control-group ]] || fail 'upgrade requires KillMode=control-group'
service_user="$(unit_value User 2>/dev/null || true)"
[[ -z "$service_user" || "$service_user" == root ]] || fail 'non-root service users require a manual upgrade'
read -r -a command_parts <<< "$exec_start"
layout=''
if [[ ${#command_parts[@]} == 4 && "${command_parts[0]}" == */runtime.sh && "${command_parts[2]}" == */oss-transfer.jar ]]; then
    layout=native; runtime_path="${command_parts[0]}"; java_bin="${command_parts[1]}"; jar="${command_parts[2]}"; config="${command_parts[3]}"
    install_dir="$(dirname "$jar")"
    [[ "$runtime_path" == "$install_dir/runtime.sh" && "$config" == */application.yml ]] || fail 'unsupported native service command'
elif [[ ${#command_parts[@]} == 3 && "${command_parts[1]}" == -jar ]]; then
    layout=legacy; java_bin="${command_parts[0]}"; jar="${command_parts[2]}"; install_dir="$work_dir"; config="$work_dir/application.yml"
    [[ "$jar" == "$work_dir/transfer-tools-1.0.0.jar" || "$jar" == "$work_dir/oss-transfer.jar" ]] || fail 'unsupported legacy JAR location'
else
    fail 'unrecognized service command; upgrade manually with the existing configuration'
fi
for path in "$install_dir" "$jar" "$config"; do safe_path "$path"; done
[[ -f "$jar" && -f "$config" ]] || fail 'the existing JAR or application.yml is missing'
if grep -Eq '^(---|\.\.\.)[[:space:]]*($|#)|^(server|transfer|rocksdb|auth):|^spring\.(config\.|profiles\.active:)' "$config"; then
    fail 'nested YAML, multiple YAML documents or Spring configuration overrides require a manual upgrade'
fi
for other_config in "$work_dir/application.properties" "$work_dir/config/application.yml" "$work_dir/config/application.properties"; do
    [[ ! -e "$other_config" ]] || fail 'additional Spring configuration files require a manual upgrade'
done
[[ "$config" == "$work_dir/application.yml" || ! -e "$work_dir/application.yml" ]] || fail 'additional working-directory configuration requires a manual upgrade'
# The generated configurations use flat YAML. Only read the handful of safe scalar
# fields needed here; complex YAML and substitutions must be reviewed manually.
scalar() {
    awk -v key="$1" '
        index($0,key ":")==1 {
            n++; value=substr($0,length(key)+2); sub(/^[[:space:]]+/,"",value); sub(/[[:space:]]+$/,"",value)
            if (value ~ /^\047/) {if (value !~ /\047$/) exit 2; value=substr(value,2,length(value)-2)}
            else if (value ~ /^"/) {if (value !~ /"$/) exit 2; value=substr(value,2,length(value)-2)}
            else sub(/[[:space:]]+#.*$/,"",value)
        }
        END {if(n>1)exit 2;print value}
    ' "$config"
}
role="$(scalar transfer.role)" || fail 'ambiguous transfer.role configuration'
if [[ "$layout" == legacy ]]; then
    master_ip="$(scalar transfer.master-ip)"; local_ip="$(scalar transfer.local-ip)"
    [[ -n "$master_ip" && "$master_ip" == "$local_ip" && ( -z "$role" || "$role" == master ) ]] || fail 'legacy worker conversion requires a new agent invitation; automatic upgrade supports the legacy master only'
    role=master
else
    [[ "$role" == master || "$role" == agent ]] || fail 'native configuration must declare transfer.role'
fi
reset_password="$(scalar auth.default.reset-password-on-startup)"
case "${reset_password,,}" in
    ''|false|no|off|0) ;;
    *) fail 'disable auth.default.reset-password-on-startup before upgrading';;
esac
port="$(scalar server.port)"
# Spring placeholder, compared literally.
# shellcheck disable=SC2016
if [[ -z "$port" || "$port" == '${transfer.port:1685}' ]]; then port="$(scalar transfer.port)"; port="${port:-1685}"; fi
if ! [[ "$port" =~ ^[0-9]{1,5}$ ]] || ! ((10#$port >= 1 && 10#$port <= 65535)); then fail 'cannot resolve the configured server port'; fi
port="$((10#$port))"
remove_port_killer=0
pre_start="$(unit_value ExecStartPre 2>/dev/null || true)"
if [[ -n "$pre_start" ]]; then
    expected_pre_start="$(cat <<'LEGACY'
/bin/bash -c 'PID=$(netstat -tlnp 2>/dev/null | grep ":@PORT@ " | awk "{print \\$7}" | cut -d/ -f1); if [ -n "$PID" ]; then echo "Killing existing process $PID on port @PORT@"; kill -9 $PID; sleep 2; fi'
LEGACY
)"
    expected_pre_start="${expected_pre_start//@PORT@/$port}"
    [[ "$layout" == legacy && "$pre_start" == "$expected_pre_start" ]] || fail 'unknown pre-start command; automatic upgrade refused'
    remove_port_killer=1
    printf 'Legacy port-killing pre-start command will be removed, including on rollback.\n'
fi
cli_server="http://127.0.0.1:$port"
if [[ "$role" == agent ]]; then
    cli_server="$(scalar transfer.agent.master-url)"
    [[ "$cli_server" =~ ^https?://[A-Za-z0-9.-]+(:[0-9]{1,5})?$ ]] || fail 'cannot resolve the agent master URL'
fi
db_path="$(scalar rocksdb.path)"; db_path="${db_path:-./data/rocksdb}"
if [[ "$db_path" != /* ]]; then db_path="$work_dir/${db_path#./}"; fi
db_path="${db_path%/}"
safe_path "$db_path"
[[ "$db_path" =~ ^/[^/]+/[^/]+/[^/]+ ]] || fail 'database path must not be a top-level system directory'
# Never allow database rollback to remove a deployment or a filesystem root.
[[ "$db_path" != "$work_dir" && "$db_path" != "$install_dir" && "$db_path" != "$(dirname "$config")" && "$db_path" != /var && "$db_path" != /var/lib && "$db_path" != /tmp ]] || fail 'unsafe database directory'
for protected in "$work_dir" "$install_dir" "$(dirname "$config")"; do [[ "$protected/" != "$db_path/"* ]] || fail 'database path contains installation files'; done
[[ -d "$db_path" ]] || fail 'existing database not found; refusing to start with an empty database'
[[ -z "$(find "$db_path" -type l -print -quit)" ]] || fail 'database contains symbolic links; manual backup is required'
mounts="$(findmnt --noheadings --raw --output TARGET)" || fail 'cannot inspect database mount points'
while IFS= read -r mount_path; do
    [[ "$mount_path" != "$db_path" && "$mount_path" != "$db_path/"* ]] || fail 'database mount points require a manual snapshot and upgrade'
done <<< "$mounts"
[[ -f "$db_path/CURRENT" && "$(cat "$db_path/CURRENT")" =~ ^MANIFEST-[0-9]+$ ]] || fail 'configured database directory is not a recognized RocksDB database'
for protected in "$work_dir" "$install_dir" "$db_path" "$(dirname "$config")"; do
    [[ "$backup_base/" != "$protected/"* && "$protected/" != "$backup_base/"* ]] || fail 'backup directory must be separate from the installation, configuration and data'
done
original_state="$(systemctl show "$service_name.service" -p ActiveState --value)"
case "$original_state" in active|inactive|failed) ;; *) fail 'service is changing state; retry after it settles';; esac
printf 'Service: %s\nLayout: %s\nRole: %s\nProgram: %s\nConfiguration: %s\nDatabase: %s\nPort: %s\nState: %s\n' "$service_name" "$layout" "$role" "$jar" "$config" "$db_path" "$port" "$original_state"
[[ "$inspect" == 0 ]] || exit 0
[[ -n "$package_dir" ]] || fail '--package-dir is required for an upgrade'
safe_path "$package_dir"
for protected in "$install_dir" "$db_path" "$(dirname "$config")"; do
    [[ "$package_dir/" != "$protected/"* ]] || fail 'extract the new package outside the existing installation and data'
done
preflight="$(bash "$here/preflight-node.sh" "$java_bin")" || fail 'Java preflight failed; the existing service has not been stopped'
IFS=$'\t' read -r architecture checked_java major <<< "$preflight"
[[ "$checked_java" == "$java_bin" && "$major" =~ ^[0-9]+$ && "$major" -ge 8 ]] || fail 'Java preflight returned a different executable'
case "$architecture" in x86_64) cli_arch=amd64;; aarch64|arm64) cli_arch=arm64;; *) fail 'unsupported architecture';; esac
for required in oss-transfer.jar "oss-transfer-cli-$cli_arch" VERSION deploy/runtime.sh deploy/wait-node-ready.sh; do
    safe_path "$package_dir/$required"
    [[ -f "$package_dir/$required" ]] || fail "package is missing $required"
done
if [[ "$role" == master ]]; then
    for required in agent-bundle.tar.gz agent-bundle.tar.gz.sha256; do
        safe_path "$package_dir/$required"
        [[ -f "$package_dir/$required" ]] || fail "master upgrade package is missing $required"
    done
    expected="$(awk 'NR==1 {print $1}' "$package_dir/agent-bundle.tar.gz.sha256")"
    [[ "$expected" =~ ^[a-fA-F0-9]{64}$ ]] || fail 'invalid agent bundle checksum'
    actual="$(sha256sum "$package_dir/agent-bundle.tar.gz" | awk '{print $1}')"
    [[ "${actual,,}" == "${expected,,}" ]] || fail 'agent bundle checksum mismatch'
fi
if [[ "$yes" == 0 ]]; then
    printf 'Stop this service, back up its database, and upgrade? [y/N]: '
    read -r answer || fail 'confirmation is required'
    [[ "$answer" == y || "$answer" == Y ]] || exit 0
fi
# Backup is outside the install and database trees, with credentials readable only by root.
mkdir -p "$backup_base"
backup="$(mktemp -d "$backup_base/$service_name-$(date -u +%Y%m%dT%H%M%SZ)-XXXXXX")"
chmod 0700 "$backup"
printf 'Backup: %s\n' "$backup"
paths=("$unit" "$config" "$jar" "$cli_path" "$install_dir/oss-transfer-cli-bin" "$install_dir/VERSION" "$install_dir/runtime.sh" "$install_dir/agent-bundle.tar.gz" "$install_dir/agent-bundle.tar.gz.sha256")
if [[ -f "$(dirname "$config")/admin-password" ]]; then paths+=("$(dirname "$config")/admin-password"); fi
declare -A unique_paths=()
for path in "${paths[@]}"; do
    safe_path "$path"
    [[ -z "${unique_paths[$path]:-}" ]] || fail 'CLI path overlaps an installation file'
    unique_paths[$path]=1
    [[ "$path/" != "$db_path/"* ]] || fail 'installation file is inside the database directory'
    [[ ! -e "$path" || -f "$path" ]] || fail "expected a regular file: $path"
done
check_space() {
    local required_kb=102400 available_kb path size
    for path in "$db_path" "${paths[@]}"; do
        if [[ -e "$path" ]]; then size="$(du -sk -- "$path" | awk '{print $1}')"; required_kb=$((required_kb + size)); fi
    done
    available_kb="$(df -Pk "$backup" | awk 'END {print $4}')"
    [[ "$available_kb" =~ ^[0-9]+$ && "$required_kb" -le "$available_kb" ]] || fail 'not enough free space for the database and file backup'
}
check_space
# Save this even if a later database backup fails: the legacy kill hook must never run again.
cp -a -- "$unit" "$backup/original-unit"
port_free() {
    local listeners
    listeners="$(timeout 5 ss -H -ltnp "sport = :$port")" || return 1
    [[ -z "$listeners" ]]
}
disable_port_killer() {
    if [[ "$remove_port_killer" == 1 ]]; then
        awk '!/^ExecStartPre=/' "$unit" > "$backup/unit-without-port-killer" || return 1
        cat "$backup/unit-without-port-killer" > "$unit" || return 1
        systemctl daemon-reload
    fi
}
stopped=0 changed=0 completed=0 db_existed=0
rollback() {
    local status=$? restore_failed=0 path index
    trap - EXIT INT TERM
    if [[ "$stopped" == 1 && "$completed" == 0 ]]; then
        printf 'Upgrade did not complete; restoring the previous installation.\n' >&2
        if ! systemctl stop "$service_name.service" || [[ "$(systemctl show "$service_name.service" -p MainPID --value)" != 0 ]]; then
            printf 'Rollback stopped: cannot confirm the service is stopped. Backup: %s\n' "$backup" >&2
            exit 1
        fi
        if [[ "$changed" == 1 ]]; then
            for index in "${!paths[@]}"; do
                path="${paths[$index]}"
                if [[ -f "$backup/files/$index" ]]; then cp -a -- "$backup/files/$index" "$path" || restore_failed=1;
                else rm -f -- "$path" || restore_failed=1; fi
            done
            # Database paths were validated and snapshotted before any new code ran.
            rm -rf -- "$db_path" || restore_failed=1
            if [[ "$db_existed" == 1 ]]; then cp -a -- "$backup/database" "$db_path" || restore_failed=1; fi
            systemctl daemon-reload || restore_failed=1
        fi
        if [[ "$restore_failed" == 0 ]]; then disable_port_killer || restore_failed=1; fi
        if [[ "$restore_failed" == 0 && "$original_state" == active ]]; then
            if ! port_free; then
                printf 'Rollback left the service stopped: its port is occupied.\n' >&2
                restore_failed=1
            elif ! systemctl reset-failed "$service_name.service" || ! systemctl start "$service_name.service" || ! bash "$here/wait-node-ready.sh" 127.0.0.1 "$port" 120 "$service_name"; then restore_failed=1; fi
        fi
        if [[ "$restore_failed" == 0 ]]; then printf 'Previous files and service state restored. Backup: %s\n' "$backup" >&2;
        else printf 'Rollback needs attention. Service left stopped when possible. Backup: %s\n' "$backup" >&2; status=1; fi
    fi
    exit "$status"
}
trap rollback EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
systemctl stop "$service_name.service" || fail 'could not stop the service; no program files were replaced'
[[ "$(systemctl show "$service_name.service" -p MainPID --value)" == 0 ]] || fail 'the service still has a running process; no program files were replaced'
stopped=1
port_free || fail 'service port is occupied; no other process will be stopped'
check_space
mkdir "$backup/files"
for index in "${!paths[@]}"; do
    path="${paths[$index]}"
    printf '%s\t%s\n' "$index" "$path" >> "$backup/paths.tsv"
    if [[ -f "$path" ]]; then cp -a -- "$path" "$backup/files/$index"; fi
done
if [[ -d "$db_path" ]]; then cp -a -- "$db_path" "$backup/database"; db_existed=1; fi
printf '%s\n' "$original_state" > "$backup/original-state"
changed=1
install -m 0644 "$package_dir/oss-transfer.jar" "$jar"
install -m 0755 "$package_dir/oss-transfer-cli-$cli_arch" "$install_dir/oss-transfer-cli-bin"
install -m 0644 "$package_dir/VERSION" "$install_dir/VERSION"
if [[ "$layout" == native ]]; then install -m 0755 "$package_dir/deploy/runtime.sh" "$install_dir/runtime.sh"; fi
if [[ "$role" == master ]]; then
    install -m 0644 "$package_dir/agent-bundle.tar.gz" "$install_dir/agent-bundle.tar.gz"
    if [[ -f "$package_dir/agent-bundle.tar.gz.sha256" ]]; then install -m 0644 "$package_dir/agent-bundle.tar.gz.sha256" "$install_dir/agent-bundle.tar.gz.sha256"; fi
fi
if [[ "$layout" == legacy ]]; then
    # Keep all existing settings, including credentials and relative database paths.
    # Make the master role explicit; the bundle enables agent enrollment.
    awk '!/^transfer\.role:/ && !/^transfer\.agent\.package-path:/' "$config" > "$backup/upgrade-application.yml"
    printf '\ntransfer.role: master\ntransfer.agent.package-path: %s/agent-bundle.tar.gz\n' "$install_dir" >> "$backup/upgrade-application.yml"
    cat "$backup/upgrade-application.yml" > "$config"
fi
# Both old binary CLIs and current wrappers are replaced with the current local launcher.
mkdir -p "$(dirname "$cli_path")"
cat > "$cli_path" <<WRAPPER
#!/usr/bin/env bash
set -euo pipefail
export OSS_TRANSFER_CONFIG_FILE='$config'
export OSS_TRANSFER_MASTER_SERVER='$cli_server'
cd '$(dirname "$config")'
exec '$install_dir/oss-transfer-cli-bin' "\$@"
WRAPPER
chmod 0755 "$cli_path"
disable_port_killer
port_free || fail 'service port is occupied; no other process will be stopped'
systemctl reset-failed "$service_name.service"
systemctl start "$service_name.service"
bash "$here/wait-node-ready.sh" 127.0.0.1 "$port" 120 "$service_name" || fail 'new version did not become ready'
completed=1
printf 'Upgraded %s. Configuration and data paths were retained.\nBackup: %s\n' "$service_name" "$backup"
