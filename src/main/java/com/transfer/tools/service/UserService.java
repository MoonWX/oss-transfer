package com.transfer.tools.service;

import com.transfer.tools.model.User;
import com.transfer.tools.storage.RocksDBService;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import javax.annotation.PostConstruct;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.SecureRandom;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ConcurrentMap;

/**
 * 用户管理服务：负责用户注册、登录校验、token 会话管理。
 * 用户数据持久化在 RocksDB，密码以 salt + SHA-256 哈希存储。
 */
@Slf4j
@Service
public class UserService {

    /** RocksDB 中用户数据的 key 前缀 */
    private static final String USER_KEY_PREFIX = "user:";

    /** 默认管理员用户名 */
    @Value("${auth.default.username:admin}")
    private String defaultUsername;

    /**
     * 默认管理员密码。支持两种形式：
     * 1. 明文（默认）：仅在首次启动时按此密码创建账号。
     * 2. 哈希（格式 salt:hash）：直接作为密码哈希存储，用于手动指定哈希。
     * 若留空（auth.default.password 不配置），首次启动时自动生成强密码。
     */
    @Value("${auth.default.password:}")
    private String defaultPassword;

    /** 仅找回密码时显式启用；默认不覆盖已存在账号的密码。 */
    @Value("${auth.default.reset-password-on-startup:false}")
    private boolean resetPasswordOnStartup;

    /** token 有效期（毫秒），默认 24 小时 */
    @Value("${auth.token.expire:86400000}")
    private long tokenExpire;

    @Autowired
    private RocksDBService rocksDBService;
    @Autowired(required = false)
    private com.transfer.tools.config.DistributedConfig distributedConfig;

    /** token -> username 的内存会话映射 */
    private final ConcurrentMap<String, String> tokenMap = new ConcurrentHashMap<>();

    /** token -> 过期时间 */
    private final ConcurrentMap<String, Long> tokenExpireMap = new ConcurrentHashMap<>();

    @PostConstruct
    public void init() {
        if (distributedConfig != null && distributedConfig.isAgent()) return;
        if (!existsUser(defaultUsername)) {
            // 首次启动：创建默认管理员账号
            String password;
            boolean autoGenerated = false;
            if (defaultPassword != null && !defaultPassword.trim().isEmpty()) {
                password = defaultPassword.trim();
            } else {
                password = generateStrongPassword();
                autoGenerated = true;
            }
            User admin = new User();
            admin.setUsername(defaultUsername);
            admin.setPasswordHash(toPasswordHash(password));
            admin.setDisplayName("系统管理员");
            admin.setRole("admin");
            admin.setCreateTime(System.currentTimeMillis());
            admin.setLastLoginTime(0);
            saveUser(admin);
            log.info("已创建默认管理员账号: {}", defaultUsername);
            if (autoGenerated) {
                log.warn("================================================================");
                log.warn("【重要】已为账号 [{}] 自动生成强密码，请立即保存：", defaultUsername);
                log.warn("  密码: {}", password);
                log.warn("  如密码丢失，配置 auth.default.password 并临时启用 auth.default.reset-password-on-startup");
                log.warn("================================================================");
            }
        } else if (resetPasswordOnStartup && defaultPassword != null && !defaultPassword.trim().isEmpty()) {
            // 初始化密码不代表重置授权，只有显式启用找回开关才覆盖已存在的账号。
            User admin = getUser(defaultUsername);
            String newHash = toPasswordHash(defaultPassword.trim());
            if (!newHash.equals(admin.getPasswordHash())) {
                admin.setPasswordHash(newHash);
                saveUser(admin);
                log.warn("已按 auth.default.reset-password-on-startup 配置重置账号 [{}] 的密码；请关闭该开关，避免下次启动再次重置", defaultUsername);
            }
        }
    }

    /**
     * 登录校验，成功后返回 token。
     */
    public String login(String username, String password) {
        User user = getUser(username);
        if (user == null) {
            return null;
        }
        if (!verifyPassword(password, user.getPasswordHash())) {
            return null;
        }
        // 更新最近登录时间
        user.setLastLoginTime(System.currentTimeMillis());
        saveUser(user);
        // 生成 token
        String token = UUID.randomUUID().toString().replace("-", "");
        tokenMap.put(token, username);
        tokenExpireMap.put(token, System.currentTimeMillis() + tokenExpire);
        return token;
    }

    /**
     * 登出，移除 token。
     */
    public void logout(String token) {
        if (token != null) {
            tokenMap.remove(token);
            tokenExpireMap.remove(token);
        }
    }

    /**
     * 根据 token 获取用户名，token 过期则返回 null。
     */
    public String getUsernameByToken(String token) {
        if (token == null) {
            return null;
        }
        Long expire = tokenExpireMap.get(token);
        if (expire == null) {
            return null;
        }
        if (System.currentTimeMillis() > expire) {
            tokenMap.remove(token);
            tokenExpireMap.remove(token);
            return null;
        }
        return tokenMap.get(token);
    }

    /**
     * 获取用户信息（不含密码哈希）。
     */
    public User getUser(String username) {
        return rocksDBService.get(USER_KEY_PREFIX + username, User.class);
    }

    /**
     * 获取用户信息并清除敏感字段。
     */
    public User getUserInfo(String username) {
        User user = getUser(username);
        if (user != null) {
            user.setPasswordHash(null);
        }
        return user;
    }

    public boolean existsUser(String username) {
        return rocksDBService.exists(USER_KEY_PREFIX + username);
    }

    public void saveUser(User user) {
        rocksDBService.put(USER_KEY_PREFIX + user.getUsername(), user);
    }

    public void deleteUser(String username) {
        rocksDBService.delete(USER_KEY_PREFIX + username);
    }

    public List<User> listUsers() {
        List<User> users = rocksDBService.scanByPrefix(USER_KEY_PREFIX, User.class);
        for (User user : users) {
            user.setPasswordHash(null);
        }
        return users;
    }

    /**
     * 创建用户（密码哈希）。
     */
    public boolean createUser(String username, String password, String displayName, String role) {
        if (existsUser(username)) {
            return false;
        }
        User user = new User();
        user.setUsername(username);
        user.setPasswordHash(hashPassword(password));
        user.setDisplayName(displayName == null ? username : displayName);
        user.setRole(role == null ? "user" : role);
        user.setCreateTime(System.currentTimeMillis());
        user.setLastLoginTime(0);
        saveUser(user);
        return true;
    }

    /**
     * 修改密码。
     */
    public boolean changePassword(String username, String oldPassword, String newPassword) {
        User user = getUser(username);
        if (user == null) {
            return false;
        }
        if (!verifyPassword(oldPassword, user.getPasswordHash())) {
            return false;
        }
        user.setPasswordHash(hashPassword(newPassword));
        saveUser(user);
        return true;
    }

    /**
     * 将配置值转换为密码哈希。
     * 若输入已是 "salt:hash" 格式（64位hex:64位hex），则直接返回；否则视为明文密码进行哈希。
     */
    private String toPasswordHash(String input) {
        if (input == null) {
            return null;
        }
        String value = input.trim();
        // 判断是否为哈希格式：salt(32位hex):hash(64位hex)
        if (value.matches("[0-9a-f]{32}:[0-9a-f]{64}")) {
            return value;
        }
        return hashPassword(value);
    }

    /**
     * 生成强密码：16 位，包含大写字母、小写字母、数字、特殊字符。
     */
    private String generateStrongPassword() {
        String upper = "ABCDEFGHJKLMNPQRSTUVWXYZ";
        String lower = "abcdefghijkmnpqrstuvwxyz";
        String digits = "23456789";
        String special = "!@#$%^&*()-_=+";
        SecureRandom random = new SecureRandom();
        StringBuilder sb = new StringBuilder(16);
        // 确保每类字符至少出现一次
        sb.append(upper.charAt(random.nextInt(upper.length())));
        sb.append(lower.charAt(random.nextInt(lower.length())));
        sb.append(digits.charAt(random.nextInt(digits.length())));
        sb.append(special.charAt(random.nextInt(special.length())));
        String all = upper + lower + digits + special;
        for (int i = 4; i < 16; i++) {
            sb.append(all.charAt(random.nextInt(all.length())));
        }
        // 打乱顺序
        char[] chars = sb.toString().toCharArray();
        for (int i = chars.length - 1; i > 0; i--) {
            int j = random.nextInt(i + 1);
            char tmp = chars[i];
            chars[i] = chars[j];
            chars[j] = tmp;
        }
        return new String(chars);
    }

    /**
     * 生成带盐的密码哈希，格式：salt:hash。
     */
    private String hashPassword(String password) {
        try {
            byte[] salt = new byte[16];
            new SecureRandom().nextBytes(salt);
            String saltHex = bytesToHex(salt);
            String hash = sha256(saltHex + password);
            return saltHex + ":" + hash;
        } catch (Exception e) {
            throw new RuntimeException("密码哈希失败", e);
        }
    }

    /**
     * 校验密码是否与哈希匹配。
     */
    private boolean verifyPassword(String password, String passwordHash) {
        if (password == null || passwordHash == null) {
            return false;
        }
        String[] parts = passwordHash.split(":");
        if (parts.length != 2) {
            return false;
        }
        String saltHex = parts[0];
        String expectedHash = parts[1];
        String actualHash = sha256(saltHex + password);
        return expectedHash.equals(actualHash);
    }

    private String sha256(String input) {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest(input.getBytes(StandardCharsets.UTF_8));
            return bytesToHex(hash);
        } catch (Exception e) {
            throw new RuntimeException("SHA-256 计算失败", e);
        }
    }

    private String bytesToHex(byte[] bytes) {
        StringBuilder sb = new StringBuilder();
        for (byte b : bytes) {
            sb.append(String.format("%02x", b));
        }
        return sb.toString();
    }
}
